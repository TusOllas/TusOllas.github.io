const grid = document.getElementById("grid-productos");

const tituloCategoria =
document.getElementById("titulo-categoria");



/* ===================================================== */
/* MOSTRAR PRODUCTOS                                     */
/* ===================================================== */

function mostrarProductos(categoriaSeleccionada){

    grid.innerHTML = "";



    const productosFiltrados =

    categoriaSeleccionada === "TODO"

    ? productos

    : productos.filter(

        producto =>

        producto.categoria === categoriaSeleccionada

    );



    productosFiltrados.forEach(producto => {

        grid.innerHTML += `

            <div class="tarjeta-producto">

                <img
                    src="${producto.imagen}"
                    class="imagen-producto"
                >

                <p class="marca-producto">

                    ${producto.marca}

                </p>

                <h2 class="nombre-producto">

                    ${producto.nombre}

                </h2>

                <div class="precio-producto">

                    ${producto.precio}

                </div>

                <button
                    class="boton-agregar"
                    data-id="${producto.id}">

                    INFORMACIÓN

                </button>

            </div>

        `;

    });

}



/* ===================================================== */
/* CAMBIO DE CATEGORÍAS                                  */
/* ===================================================== */

document.addEventListener(

    "click",

    function(event){

        const categoria =

        event.target.closest(".categoria");



        if(categoria){

            event.preventDefault();



            const categoriaSeleccionada =

            categoria.dataset.categoria;



            tituloCategoria.textContent =

            categoriaSeleccionada;



            mostrarProductos(
                categoriaSeleccionada
            );

        }



        /* ===================================================== */
        /* BOTON AGREGAR                                         */
        /* ===================================================== */

        const botonAgregar =

        event.target.closest(
            ".boton-agregar"
        );



        if(botonAgregar){

            const idProducto =

            botonAgregar.dataset.id;



            const productoSeleccionado =

            productos.find(

                producto =>

                producto.id == idProducto

            );



            localStorage.setItem(

                "productoSeleccionado",

                JSON.stringify(
                    productoSeleccionado
                )

            );



            window.location.href =

            "../Informacion/Informacion.html";

        }

    }

);



